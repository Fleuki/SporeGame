// ПАЛИТРА ИГРЫ — одна на всё, что попадает в кадр.
//
// Зачем она вообще. Замер по репозиторию до нормализации: от 500 до 4200
// уникальных цветов НА СПРАЙТ, средний тон гуляет от 27° до 297°, а два листа
// одного и того же алхимика различались по тону на 40°. Каждая картинка
// генерировалась отдельно и приносила свою палитру — отсюда и ощущение, что
// ассеты собраны из разных игр. Настоящий пиксель-арт живёт на 16–32 цветах,
// и это не ограничение ради ретро-вида, а единственный способ заставить
// картинки от разных генераций смотреться одним набором.
//
// Восемь раскладок по четыре ступени: тень, база, свет, блик. Базовые тона
// (третья колонка) — ровно те девять, что записаны в DESIGN_DOC и в промптах
// ASSET_PROMPTS.md; новое здесь только то, что у каждого появились ступени, а
// у ступеней — обязательность.
//
// МЕНЯТЬ ОСТОРОЖНО. Правка одного значения меняет ВСЕ картинки сразу (они
// пересобираются из assets/raw), и это её главное достоинство: подкрутить
// общий тон игры теперь можно одним числом, а не перерисовкой сорока файлов.

export const RAMPS = {
  // Земля, мох, фон. Самая тёмная раскладка: земля обязана быть тише всего
  // остального в кадре, иначе враги теряются в текстуре — так и было.
  moss:    ["#0d1f15", "#142c20", "#1a3d2e", "#2b5741"],
  // Грибная плоть: враги, шляпки, наросты
  fungus:  ["#2b1226", "#4a1f40", "#6b2d5c", "#9c4a86"],
  // Токсичная жёлтая: споры, свечение изнутри, кислота
  toxic:   ["#4a3d00", "#8a7000", "#c4a000", "#f0d24a"],
  // Биолюминесценция: всё, что принадлежит игроку и его склянкам
  biolum:  ["#00584a", "#009e83", "#00d4aa", "#7dffca"],
  // Кислотно-зелёная: попадания, ядовитые лужи
  acid:    ["#1d6b0c", "#2bb010", "#39ff14", "#a8ff6a"],
  // Кожа, дерево, ткань
  leather: ["#2a1a0e", "#40280f", "#5c3a21", "#8a5d3b"],
  // Противогаз, металл, тени
  iron:    ["#0a0c0b", "#1c1f1e", "#2a2a2a", "#4a4d4c"],
  // Споровая пыль, кость, свет
  spore:   ["#5c5c5c", "#8a8a8a", "#b5b5b5", "#e6e6e6"],
  // Кровь и опасность. В DESIGN_DOC этой раскладки не было вовсе — там на
  // месте «крови» стоит кислотно-зелёный, — и первый же прогон это вскрыл:
  // склянка лечения вышла из квантования розовой, потому что красному просто
  // некуда было лечь. При этом красный в игре повсюду: шкала здоровья, цифры
  // урона, рамка при попадании. Раскладка добавлена именно поэтому.
  blood:   ["#3a0d10", "#6e1a20", "#b02a33", "#ff4a55"]
};

export const PALETTE = Object.values(RAMPS).flat().map(hex=>({
  hex,
  r: parseInt(hex.slice(1,3),16),
  g: parseInt(hex.slice(3,5),16),
  b: parseInt(hex.slice(5,7),16)
}));

// ПАЛИТРА ЗЕМЛИ — обрезанная. Первый прогон нормализации показал ровно ту
// беду, ради которой всё затевалось, только с другой стороны: костяной биом
// после квантования стал БЕЛЫМ (светлые ступени споровой раскладки), а жилы
// мха — светло-серыми. Земля превратилась в самое яркое пятно кадра, а враги
// на ней — в грязь. Земля обязана быть тише всего остального, поэтому ей
// доступны только тёмные ступени: две первых у каждой раскладки, и никаких
// бликов. Костяной биом от этого не перестаёт быть костяным — он просто
// перестаёт спорить с тем, что по нему ходит.
// Потолок яркости для земли. Обрезки «две первых ступени» оказалось мало:
// костяной биом уходил в #8a8a8a и оставался вдвое светлее любого врага
// (0.37 против 0.20 по замеру), то есть по-прежнему перетягивал взгляд.
// 108 — это уровень, ниже которого лежат все тёмные ступени раскладок и выше
// которого начинаются «материальные» цвета: им место на фигурах, не под ними.
const GROUND_MAX=108;
const GROUND=Object.values(RAMPS).flatMap(r=>r.slice(0,2))
  .map(hex=>({
    hex,
    r: parseInt(hex.slice(1,3),16),
    g: parseInt(hex.slice(3,5),16),
    b: parseInt(hex.slice(5,7),16)
  }))
  .filter(c=>Math.max(c.r,c.g,c.b)<=GROUND_MAX);

// Ближайший цвет палитры. Метрика — «redmean»: обычное евклидово расстояние
// по RGB считает зелёный и синий одинаково важными, и тёмно-фиолетовое мясо
// врага уезжало в серый. Redmean дешёвый и заметно ближе к тому, что видит
// глаз, чем сырой RGB, — а честный Oklab здесь избыточен: ступеней всего 32.
const cache=new Map(), groundCache=new Map();
export function nearest(r,g,b,ground=false){
  const list=ground?GROUND:PALETTE;
  const memo=ground?groundCache:cache;
  const key=(r<<16)|(g<<8)|b;
  const hit=memo.get(key);
  if(hit!==undefined) return hit;
  let best=list[0], bestD=Infinity;
  for(const p of list){
    const rm=(p.r+r)/2;
    const dr=p.r-r, dg=p.g-g, db=p.b-b;
    const d=(2+rm/256)*dr*dr + 4*dg*dg + (2+(255-rm)/256)*db*db;
    if(d<bestD){ bestD=d; best=p; }
  }
  memo.set(key,best);
  return best;
}

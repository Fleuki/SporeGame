import { CONFIG } from "../config.js";
import { Store } from "../engine/store.js";

// РЕКОРД ЗАБЕГА.
//
// Забег заканчивался — и всё. Ни следа, ни повода начать заново: экран
// поражения показывал цифры, которые ни с чем не сравнивались. Одна строка
// «в прошлый раз было 6:40» превращает «поиграл» в «ещё раз», и это самый
// дешёвый способ дать игре причину для второго запуска.
//
// Мерилом взято ВРЕМЯ, а не уровень и не убийства — но с тех пор у забега
// появился конец (CONFIG.spawn.final), и одного времени стало мало: см.
// better() ниже, там разбор, почему пройденный забег и погибший сравниваются
// по-разному. Время — единственная мера
// прогресса в этой игре (волн нет, см. SpawnSystem), по нему считается вся
// сложность, и обмануть его нельзя: отсидеться в углу не выйдет, поток врагов
// растёт сам. Уровень и убийства показываются рядом, но рекорд ставит время.
//
// Хранилище — через Store (engine/store.js), а не напрямую: на площадке оно
// подменяется на своё, потому что в чужом iframe localStorage может быть
// недоступен вовсе — в приватном окне, при жёстких
// настройках, внутри iframe. Игра от этого страдать не должна: рекорда просто
// не будет, а забег пойдёт как шёл.

const KEY="sporegame.best";

// РЕКОРД У КАЖДОЙ СЛОЖНОСТИ СВОЙ. Один общий рекорд на все три означал бы,
// что «пройден за 15:01» на лёгкой отменяет собой любую попытку на тяжёлой, —
// то есть сложности, ради которых игрок и возвращается, обесценивали бы себя
// сами. Ключ хранения — KEY + сложность; старый общий ключ читается как
// рекорд первой сложности, чтобы у тех, кто уже играл, ничего не пропало.
export class RecordSystem {
  constructor(scope=null){ this.scope=scope; this.best=this.load(); }

  key(){ return this.scope?KEY+"."+this.scope:KEY; }

  // Хранилище подменили уже после первого чтения (площадка отдаёт своё
  // промисом — см. Store.use): рекорд надо перечитать, иначе игрок увидит
  // пустую строку рекорда там, где он на самом деле есть.
  reload(){ this.best=this.load(); }

  // Смена сложности на стартовом экране. Рекорд перечитывается, prev
  // сбрасывается: «прошлый забег» другой сложности — это не прошлый забег.
  setScope(scope){
    if(this.scope===scope) return;
    this.scope=scope; this.prev=null; this.best=this.load();
  }

  read(key){
    try{
      const raw=Store.getItem(key);
      if(!raw) return null;
      const b=JSON.parse(raw);
      return (typeof b?.time==="number")?b:null;
    }catch{ return null; }
  }

  load(){
    const own=this.read(this.key());
    if(own) return own;
    // Наследство одного общего рекорда: он был поставлен до появления
    // сложностей, то есть на первой.
    if(this.scope===CONFIG.difficulties.starter) return this.read(KEY);
    return null;
  }

  // ЧТО СЧИТАТЬ ЛУЧШИМ ЗАБЕГОМ, когда забег стало возможно ПРОЙТИ.
  //
  // Пока конца не было, правило было одно: дольше — лучше. Теперь мер две, и
  // складывать их в одну нельзя: пройденный за 15:40 забег лучше погибшего на
  // 19:00, хотя по секундам он короче. Порядок такой:
  //   * победа лучше любого поражения — это другой исход, а не другое число;
  //   * среди побед лучше БЫСТРАЯ: время финала фиксировано, и разница между
  //     двумя победами — это ровно то, за сколько добит последний босс;
  //   * среди поражений лучше долгое, как и было.
  better(run,best){
    if(!best) return true;
    if(!!run.won!==!!best.won) return !!run.won;
    return run.won ? run.time<best.time : run.time>best.time;
  }

  // Возвращает true, если рекорд побит: по этому экран итогов решает,
  // показывать ли «НОВЫЙ РЕКОРД»
  submit(run){
    const beaten=this.better(run,this.best);
    if(beaten){
      this.prev=this.best;
      this.best={time:run.time,level:run.level,kills:run.kills,won:!!run.won};
      Store.setItem(this.key(),JSON.stringify(this.best));
    } else {
      this.prev=this.best;
    }
    return beaten;
  }
}

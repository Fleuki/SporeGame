import { Store } from "../engine/store.js";

// ПЛОЩАДКА: ЯНДЕКС ИГРЫ.
//
// Игра лежит в двух местах сразу — на GitHub Pages (свой адрес, открывается
// как обычная страница) и на Яндекс Играх (чужой iframe, свой SDK, своя
// реклама). Один и тот же код обязан работать в обоих, поэтому здесь не
// «включение Яндекса», а АДАПТЕР: без SDK каждый метод молча делает ничего, и
// игра идёт как шла.
//
// Проверять это надо ровно так же — обоими способами: с подставным
// `window.YaGames` и без него. Ветка «SDK нет» ломается незаметнее: она
// проявляется только там, где никто не смотрит.
//
// Что требует площадка (критерии модерации, раздел «Технические требования»):
//   — SDK встроен и инициализирован по документации;
//   — вызван features.LoadingAPI.ready(), когда игра готова к игре;
//   — реклама только через SDK и только в логических паузах;
//   — при показе полноэкранной рекламы звук ставится на паузу;
//   — прогресс переживает уход по рекламе и возврат.

export class YandexPlatform {
  constructor(){
    this.ysdk=null;
    this.enabled=false;       // SDK ответил, методы можно звать
    this.readySent=false;
    this.readyWanted=false;   // игра уже сказала «готова», SDK ещё нет
    this.playing=false;       // что мы уже сообщили площадке
    this.wantPlaying=false;   // что происходит на самом деле
    this.lang="ru";
    this.onAdvSound=null;     // main вешает сюда глушилку звука
  }

  // ЗАПУСК. Никогда не бросает. Игра его ЖДЁТ — язык обязан быть известен до
  // первого показа интерфейса (п. 2.14), — но ждёт со сторожем: молчащий SDK
  // (свой адрес, блокировщик, оборванная сеть) не должен запирать игру на
  // экране загрузки. Сторож в boot() (main.js).
  //
  // ИНИЦИАЛИЗАЦИЮ ЗАПУСКАЕТ НЕ ЭТОТ МОДУЛЬ, А САМА СТРАНИЦА — прямо в <head>,
  // сразу за тегом SDK (см. index.html). Здесь только ЗАБИРАЕТСЯ готовый
  // промис, и разница не стилистическая: игра — это модуль из 32 файлов, и
  // `YaGames.init()`, вызванный отсюда, ждал загрузки их всех. Замер: почти
  // секунда до вызова на 60 мс сетевой задержки, на мобильном интернете —
  // секунды, и всё это время лоадер площадки стоит в «W — ожидает
  // инициализации». Это и есть «SDK встроено некорректно» (п. 1.1).
  async boot(){
    if(typeof window==="undefined") return false;
    try{
      // Промис из <head>; если страницу собрали без него (чужая разметка,
      // ручная правка), инициализируем сами — но уже с этой задержкой.
      const pending=window.ysdkReady
        || (window.YaGames&&window.YaGames.init ? window.YaGames.init() : null);
      this.ysdk=pending?await pending:null;
      if(!this.ysdk) return false;
      this.enabled=true;
      // ЯЗЫК БЕРЁТСЯ У ПЛОЩАДКИ, а не задаётся в коде — этого требуют
      // критерии модерации. Игра русскоязычная целиком и другого языка не
      // знает, поэтому здесь только чтение: появится вторая локализация —
      // выбирать её этой же строкой.
      this.lang=this.ysdk?.environment?.i18n?.lang||"ru";
      // ХРАНИЛИЩЕ ПЛОЩАДКИ. В чужом iframe localStorage принадлежит не игре,
      // и на движке WebKit (весь iOS) он режется: рекорд и банк пропадают
      // молча. Своё хранилище SDK отдаёт промисом — Store умеет принять его
      // задним числом и перечитать всё, что уже прочитано из пустоты.
      try{
        const storage=await this.ysdk.getStorage();
        if(storage) Store.use(storage);
      }catch{ /* нет — играем на localStorage, как на своём адресе */ }
      // ДОГОНЯЕМ ТО, ЧТО СЛУЧИЛОСЬ, ПОКА SDK ПОДНИМАЛСЯ. Запуск игры теперь
      // ЖДЁТ этот метод (см. boot() в main.js) — но со сторожем: если SDK
      // молчит дольше пяти секунд, игра открывается без него и живёт своей
      // жизнью. Тогда ответ приходит в уже играющую игру, и эти две строки
      // договаривают за неё всё, что она успела сказать в пустоту.
      this.sendReady();
      this.flushGameplay();
      return true;
    }catch(e){
      // Игра идёт дальше — упавший SDK не повод не дать поиграть, — но в
      // консоль это обязано попасть: «SDK не поднялся» ищут именно там, и
      // проглоченная ошибка стоила отказа по п. 1.1.
      console.warn("SDK Яндекс Игр не поднялся, игра идёт без него:",e);
      this.ysdk=null; this.enabled=false;
      return false;
    }
  }

  // ИГРА ГОТОВА. Площадка держит свой экран загрузки до этого вызова, и
  // «метод вызван не вовремя» — одна из типовых причин отказа на модерации.
  // Игра на этом уже возвращалась: «GameReady API работает некорректно, вызов
  // осуществляется после того, как игра становится доступной для
  // взаимодействия» (п. 1.19).
  //
  // Зовётся РОВНО ОДИН РАЗ и ровно в одном месте — в boot() (main.js), после
  // загрузки ассетов и ДО того, как включится ввод и покажется стартовый
  // экран. Никакого интерактивного экрана раньше этого вызова быть не должно.
  ready(){
    this.readyWanted=true;
    this.sendReady();
  }

  sendReady(){
    if(!this.enabled||!this.readyWanted||this.readySent) return;
    this.readySent=true;
    try{
      this.ysdk.features?.LoadingAPI?.ready?.();
      console.info("SDK Яндекс Игр: LoadingAPI.ready()");
    }catch(e){ console.warn("LoadingAPI.ready() не прошёл:",e); }
  }

  // ГЕЙМПЛЕЙ ИДЁТ / НЕ ИДЁТ. Площадка по этим двум вызовам понимает, играет
  // человек прямо сейчас или стоит в меню, — и не показывает рекламу поверх
  // боя. Оба защищены от повтора: звать их из каждого перехода состояния
  // проще, чем помнить, откуда уже позвали.
  // Намерение и доклад разведены нарочно: намерение появляется сразу
  // (игрок нажал «Играть»), доложить его можно только когда ответит SDK.
  gameplayStart(){ this.wantPlaying=true; this.flushGameplay(); }
  gameplayStop(){ this.wantPlaying=false; this.flushGameplay(); }

  flushGameplay(){
    if(!this.enabled||this.wantPlaying===this.playing) return;
    this.playing=this.wantPlaying;
    try{
      if(this.playing) this.ysdk.features?.GameplayAPI?.start?.();
      else this.ysdk.features?.GameplayAPI?.stop?.();
    }catch{}
  }

  // РЕКЛАМНАЯ ПАУЗА между забегами. Не «показать рекламу», а именно пауза:
  // снаружи это переход из одного экрана в другой, и `done` вызовется в
  // любом случае — показали блок, не показали, отказал ли SDK вовсе.
  //
  // Три решения, которые легко сломать «улучшением»:
  //
  // 1. МЕСТО. Блок вызывается на кнопке «ЗАНОВО»/«В МЕНЮ», то есть между
  //    забегами, а не в момент смерти. Игрок сначала читает свои цифры, и
  //    только потом, уже решив играть дальше, видит рекламу. На смерти это
  //    было бы рекламой поверх события, ради которого он играл.
  // 2. ЗВУК ГЛУШИТСЯ НА ВРЕМЯ ПОКАЗА — это требование площадки, а не
  //    вежливость: музыка игры поверх рекламного ролика читается как две
  //    сломанные вещи сразу.
  // 3. СТОРОЖ. Если SDK не ответит ни одним колбэком (сеть отвалилась,
  //    блокировщик съел скрипт), игра ОБЯЗАНА пойти дальше сама: зависший
  //    экран итогов — это отказ на модерации и, что важнее, конец игры для
  //    того, кто на него наткнулся.
  commercialBreak(done){
    // ГЕЙМПЛЕЙ НА ВРЕМЯ БЛОКА ОСТАНОВЛЕН. Блок и так вызывается только с
    // экрана итогов, где `gameplayStop()` уже прошёл, — но требование
    // площадки (п. 1.19.2) звучит про сам показ рекламы, а не про то, откуда
    // его позвали. Повтор адаптер отсеет сам, а забытый случай — нет.
    this.gameplayStop();
    if(!this.enabled||!this.ysdk?.adv?.showFullscreenAdv){ done(); return; }
    let finished=false, watchdog=0;
    const finish=()=>{
      if(finished) return;
      finished=true;
      clearTimeout(watchdog);
      this.onAdvSound?.(false);
      done();
    };
    // Сторож не снимается, а ПЕРЕВОДИТСЯ: пока блок не открылся, ждать его
    // дольше восьми секунд незачем; открытый ролик может идти минуту, и
    // обрывать его нельзя — но и висеть на нём вечно тоже (колбэк закрытия
    // может не прийти вовсе, если вкладку увели в фон посреди показа).
    const guard=(ms)=>{ clearTimeout(watchdog); watchdog=setTimeout(finish,ms); };
    guard(8000);
    try{
      this.ysdk.adv.showFullscreenAdv({
        callbacks:{
          onOpen:()=>{ guard(180000); this.onAdvSound?.(true); },
          onClose:()=>finish(),
          onError:()=>finish(),
        }
      });
    }catch{ finish(); }
  }
}
